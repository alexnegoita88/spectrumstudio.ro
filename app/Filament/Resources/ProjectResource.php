<?php

namespace App\Filament\Resources;

use App\Filament\Resources\ProjectResource\Pages;
use App\Filament\Resources\ProjectResource\RelationManagers;
use App\Models\Project;
use Filament\Forms;
use Filament\Forms\Components\DateTimePicker;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Group;
use Filament\Forms\Components\RichEditor;
use Filament\Forms\Components\Section;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Forms\Form;
use Filament\Forms\Set;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Columns\BadgeColumn;
use Filament\Tables\Columns\ImageColumn;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\SoftDeletingScope;

class ProjectResource extends Resource
{
    protected static ?string $model = Project::class;

    protected static ?string $navigationIcon = 'heroicon-o-document-plus';

    protected static ?string $navigationGroup = 'Content';


    public static function form(Form $form): Form
    {
        return $form->schema([
            Group::make()->schema([

                Section::make('Create a project')
                    ->description('Here you can create a new project')
                    ->schema([
                        TextInput::make('title')
                            ->label('Title')
                            ->columnSpanFull()
                            ->required()
                            ->maxLength(2048)
                            ->reactive()
                            ->afterStateUpdated(function ($state, $set) {
                                $set('slug', \Illuminate\Support\Str::slug($state));
                            })->live(false, 800, true),


                        RichEditor::make('body')
                            ->label('Content')
                            ->required()
                            ->columnSpanFull()
                        ,
                        
                    ]),
            ])->columns(3)->columnSpan(2),
            Group::make()->schema([
                Section::make('Meta')->schema([
                    TextInput::make('slug')
                        ->required()
                        ->unique(ignoreRecord: true)
                        ->label('Slug (Autogenerated --- must be unique) DO NOT TRY TO WRITE IN THIS FIELD')
                        ->readOnly()
                        ->columnSpanFull(),
                ]),
           
                Section::make('Pictures')->schema([
                    FileUpload::make('pictures')
                        ->label('Project pictures (max. 5)')
                        ->required()
                        ->multiple(true)
                        ->maxFiles(5)
                        ->disk('public')
                        ->preserveFilenames()
                        ->downloadable()
                        ->openable()
                        ->imageEditor()
                        ->imageEditorAspectRatios(['4:3','3:4', '16:9', '9:16', '1:1'])
                        // ->maxFiles(5)
                        ->columnSpanFull()
                        ,
                ]),
           
                Section::make('Visibility')->schema([
                    Toggle::make('active')
                        ->label('Published')
                        ->required()
                        ->columnSpanFull()
                        ->default(true),
                    DateTimePicker::make('published_at')
                        ->native(false)
                        ->default('now')
                        ->seconds(false)
                        ->displayFormat('d F Y H:i')
                        ->locale('en')
                        // ->timezone('Europe/Bucharest')


                ])
            ]),

        ])->columns(3)
        ;
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                Tables\Columns\TextColumn::make('id')
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->sortable(),

                    ImageColumn::make('pictures')
                    ->getStateUsing(fn (Project $record) => isset($record->pictures[0]) ? $record->pictures[0] : null)
                    ->toggleable(true),
                

                TextColumn::make('title')
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()

                ,


                Tables\Columns\TextColumn::make('slug')
                    ->sortable()
                    ->searchable()
                    ->toggleable()
                    ,

                BadgeColumn::make('active')
                    ->getStateUsing(function (Project $post) {
                        return $post->active == 1 ? "Active" : "Inactive";
                    })
                    ->sortable()
                    ->color(fn ($state) => match($state) {
                        'Active' => 'success',
                        'Inactive' => 'danger',
                    })
                    ->toggleable()
                    ->label('Status'),
                
                TextColumn::make('user.name')
                    ->toggleable()
                    ->toggledHiddenByDefault()
                    ->sortable()
                    ->label('Author')
                ,
                
                TextColumn::make('updater.name')
                    ->toggleable()
                    ->toggledHiddenByDefault()
                    ->sortable()
                    ->label('Updated By')
                ,


                TextColumn::make('published_at')
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->sortable()
            ])
            ->filters([
                SelectFilter::make('active')
                    ->label('Status')
                    ->options([
                        '1' => 'Active',
                        '0' => 'Inactive',
                    ]),
                SelectFilter::make('author')
                    ->relationship('user', 'name')
                    ->label('Author')
                    ->options([
                        
                    ]),
                SelectFilter::make('updater')
                    ->relationship('updater', 'name')
                    ->label('Last update by')
                    ->options([
                        
                    ]),            ])
            ->actions([
                Tables\Actions\ViewAction::make(),
                Tables\Actions\EditAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ])->defaultSort('id', 'desc');
    }

    public static function getRelations(): array
    {
        return [
            //
        ];
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListProjects::route('/'),
            'create' => Pages\CreateProject::route('/create'),
            'edit' => Pages\EditProject::route('/{record}/edit'),
        ];
    }
}
