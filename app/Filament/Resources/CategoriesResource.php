<?php

namespace App\Filament\Resources;

use App\Filament\Resources\CategoriesResource\Pages;
use App\Filament\Resources\CategoriesResource\RelationManagers;
use App\Models\Category;
use Filament\Forms;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Group;
use Filament\Forms\Components\RichEditor;
use Filament\Forms\Components\Section;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Columns\ImageColumn;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\SoftDeletingScope;

class CategoriesResource extends Resource
{
    protected static ?string $model = Category::class;

    protected static ?string $navigationIcon = 'heroicon-o-rectangle-group';

    protected static ?string $navigationGroup = 'Products';


    protected static ?string $label = 'Category';

    // protected static ?string $pluralLabel = 'Categorii';


    public static function form(Form $form): Form
    {
        return $form
            ->schema([
                Group::make()->schema([
                    Section::make('Add a new category')->schema([
    
                        TextInput::make('name')
                            ->label('Name')
                            ->columnSpanFull()
                            ->required()
                            ->maxLength(255)
                            ->reactive()
                            ->afterStateUpdated(function ($state, $set) {
                                $set('slug', \Illuminate\Support\Str::slug($state));
                            })->live(false, 800, true)
                        ,
                        Select::make('parent_id')
                            ->relationship('parent', 'name')
                            ->searchable()
                            ->nullable()
                        ,
                        RichEditor::make('description')
                            ->label('Description')
                            ->columnSpanFull()
                            ->required()
                    ,
                    ])
                ])->columns(2)->columnSpan(2),
                Group::make()->schema([
                    Section::make('Meta')->schema([
                        FileUpload::make('featured_picture')
                            ->label('Featured Image')
                            ->required()
                            ->multiple(false)
                            ->preserveFilenames()
                            ->downloadable()
                            ->openable()
                            ->imageEditor()
                            ->imageEditorAspectRatios(['4:3','3:4', '16:9', '9:16', '1:1'])
                            ->maxFiles(1)
                            ->disk('uploads') // Specificăm disk-ul personalizat
                            ->visibility('public')
                            ->columnSpanFull()
        
    
                    ]),
                    Section::make('Meta')->schema([
                        TextInput::make('slug')
                            ->required()
                            ->unique(ignoreRecord: true)
                            ->label('Slug (Autogenerated --- must be unique) DO NOT TRY TO WRITE IN THIS FIELD')
                            ->readOnly()
                            ->columnSpanFull(),
        
    
                    ])
                ])->columns(1),
            ])->columns(3);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                TextColumn::make('id')
                ->toggleable(true)
                ->toggledHiddenByDefault()
                ->sortable()
                ,

                ImageColumn::make('featured_picture')
                ->label('Picture')
                ->toggleable(true)
                ->toggledHiddenByDefault(true)
                ->disk('uploads') // Specificăm disk-ul personalizat
            
                ,
                
                TextColumn::make('name')
                    ->limit(80)
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()
                ,

                TextColumn::make('parent.name')
                    ->label('Parent')
                    ->limit(80)
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()
                ,
                TextColumn::make('slug')
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()            
            ])
            ->filters([
                //
            ])
            ->actions([
                Tables\Actions\ViewAction::make(),
                Tables\Actions\EditAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getRelations(): array
    {
        return [
            //
        ];
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListCategories::route('/'),
            'create' => Pages\CreateCategories::route('/create'),
            'edit' => Pages\EditCategories::route('/{record}/edit'),
        ];
    }
}
