<?php

namespace App\Filament\Resources;

use App\Filament\Resources\PostResource\Pages;
use App\Filament\Resources\PostResource\RelationManagers;
use App\Models\Post;
use Auth;
use DeepCopy\TypeFilter\Date\DateIntervalFilter;
use Filament\Forms;
use Filament\Forms\Components\DateTimePicker;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Group;
use Filament\Forms\Components\Hidden;
use Filament\Forms\Components\RichEditor;
use Filament\Forms\Components\Section;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Columns\BadgeColumn;
use Filament\Tables\Columns\ImageColumn;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\Filter;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\SoftDeletingScope;

class PostResource extends Resource
{
    protected static ?string $model = Post::class;

    protected static ?string $navigationIcon = 'heroicon-o-newspaper';

    protected static ?string $navigationGroup = 'Content';



    public static function form(Form $form): Form
    {

        return $form
            ->schema([
                Group::make()->schema([
                    Section::make('Create a blog post')->schema([

                        TextInput::make('title')
                        ->label('Title')
                        ->columnSpanFull()
                        ->required()
                        ->maxLength(255)
                        ->reactive()
                        ->afterStateUpdated(function ($state, $set) {
                            $set('slug', \Illuminate\Support\Str::slug($state));
                        })->live(false, 800, true)
                    ,
    
                    RichEditor::make('body')
                        ->label('Content')
                        ->columnSpanFull()
                        ->required()
                        ->maxLength(2048)
                        ->reactive()
                        ->afterStateUpdated(function ($state, $set) {
                            $set('excerpt', \Illuminate\Support\Str::excerpt($state));
                        })->live(false, 800, true)
                    ,
                    ])
                ])->columns(2)->columnSpan(2),

                Group::make()->schema([
                    Section::make('Meta')->schema([
                        FileUpload::make('featured_image')
                            ->label('Featured image')
                            ->required()
                            // ->multiple()
                            ->disk('public')
                            ->preserveFilenames()
                            ->downloadable()
                            ->openable()
                            ->imageEditor()
                            ->imageEditorAspectRatios(['4:3','3:4', '16:9', '9:16', '1:1'])
                            // ->maxFiles(5)
                            ->columnSpanFull()
                        ,
                        TextInput::make('slug')
                            ->required()
                            ->unique(ignoreRecord: true)
                            ->label('Slug (Autogenerated --- must be unique) DO NOT TRY TO WRITE IN THIS FIELD')
                            ->readOnly()
                            ->columnSpanFull(),
        
                        Toggle::make('active')
                            ->label('Published')
                            ->required()
                            ->columnSpanFull()
                            ->default(true),
        
                        DateTimePicker::make('published_at')
                            ->native(false)
                            ->default('now')
                            ->seconds(false)
                            ->displayFormat('d F Y H:i')
                            ->locale('en')
                        ,
        
                        TextInput::make('excerpt')
                            ->required()
                            ->unique(ignoreRecord: true)
                            ->label('Excerpt (Autogenerated) DO NOT TRY TO WRITE IN THIS FIELD')
                            ->readOnly()
                            ->columnSpanFull(),
                    ])
                ])->columns(1),
                

            ])->columns(3);
    }

    public static function table(Table $table): Table
    {


        return $table
            ->columns([

                TextColumn::make('id')
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->sortable()
                ,
                
                ImageColumn::make('featured_image')
                ->toggleable(true)

                ,

                TextColumn::make('title')
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()

                ,


                
                TextColumn::make('slug')
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->sortable()
                ,
                
                BadgeColumn::make('active')
                    ->getStateUsing(function (Post $post) {
                        return $post->active == 1 ? "Active" : "Inactive";
                    })
                    ->sortable()
                    ->color(fn ($state) => match($state) {
                        'Active' => 'success',
                        'Inactive' => 'danger',
                    })
                    ->toggleable()
                    ->label('Status'),
                
                TextColumn::make('user.name')
                    ->toggleable()
                    ->toggledHiddenByDefault()
                    ->sortable()
                    ->label('Author')
                ,
                
                TextColumn::make('updater.name')
                    ->toggleable()
                    ->toggledHiddenByDefault()
                    ->sortable()
                    ->label('Updated By')
                ,


                TextColumn::make('published_at')
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->sortable()
            ])

            ->defaultSort('id', 'desc')

            ->filters([
                SelectFilter::make('active')
                    ->label('Status')
                    ->options([
                        '1' => 'Active',
                        '0' => 'Inactive',
                    ]),
                SelectFilter::make('author')
                    ->relationship('user', 'name')
                    ->label('Author')
                    ->options([
                        
                    ]),
                SelectFilter::make('updater')
                    ->relationship('updater', 'name')
                    ->label('Last update by')
                    ->options([
                        
                    ]),
            ])
            ->actions([
                Tables\Actions\ViewAction::make(),

                Tables\Actions\EditAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getRelations(): array
    {
        return [
            //
        ];
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListPosts::route('/'),
            'create' => Pages\CreatePost::route('/create'),
            'edit' => Pages\EditPost::route('/{record}/edit'),
        ];
    }
}
