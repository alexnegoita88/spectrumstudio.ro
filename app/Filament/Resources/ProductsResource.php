<?php

namespace App\Filament\Resources;

use App\Filament\Resources\ProductsResource\Pages;
use App\Filament\Resources\ProductsResource\RelationManagers;
use App\Models\Product;
use Filament\Forms;
use Filament\Forms\Components\DateTimePicker;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Group;
use Filament\Forms\Components\RichEditor;
use Filament\Forms\Components\Section;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Columns\BadgeColumn;
use Filament\Tables\Columns\ImageColumn;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\SoftDeletingScope;

class ProductsResource extends Resource
{
    protected static ?string $model = Product::class;

    protected static ?string $navigationIcon = 'heroicon-o-shopping-cart';

    protected static ?string $label = 'Article';

    // protected static ?string $pluralLabel = 'Articole';

    protected static ?string $navigationGroup = 'Products';

    public static function form(Form $form): Form
    {
        return $form
        ->schema([
            Group::make()->schema([
                Section::make('Add a new product')->schema([

                    TextInput::make('name')
                        ->label('Name')
                        ->columnSpanFull()
                        ->required()
                        ->maxLength(255)
                        ->reactive()
                        ->afterStateUpdated(function ($state, $set) {
                            $set('slug', \Illuminate\Support\Str::slug($state));
                        })->live(false, 800, true)
                    ,
                    Select::make('categories')
                        ->relationship('categories', 'name')
                        ->multiple()
                        ->searchable()
                    ,
                    RichEditor::make('description')
                        ->label('Description')
                        ->columnSpanFull()
                        ->required()
                ,
                ])
            ])->columns(2)->columnSpan(2),

            Group::make()->schema([
                Section::make('Meta')->schema([
                    FileUpload::make('pictures')
                        ->label('Images (max. 5 files)')
                        ->required()
                        ->multiple(true)
                        ->disk('public')
                        ->preserveFilenames()
                        ->downloadable()
                        ->openable()
                        ->imageEditor()
                        ->imageEditorAspectRatios(['4:3','3:4', '16:9', '9:16', '1:1'])
                        ->maxFiles(5)
                        ->columnSpanFull()

                    ,
                    TextInput::make('slug')
                        ->required()
                        ->unique(ignoreRecord: true)
                        ->label('Slug (Autogenerated --- must be unique) DO NOT TRY TO WRITE IN THIS FIELD')
                        ->readOnly()
                        ->columnSpanFull(),
    
                    Toggle::make('active')
                        ->label('Published')
                        ->required()
                        ->columnSpanFull()
                        ->default(true),

                ])
            ])->columns(1),
            

        ])->columns(3);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                TextColumn::make('id')
                ->toggleable(true)
                ->toggledHiddenByDefault()
                ->sortable()
                ,

                ImageColumn::make('pictures')
                ->getStateUsing(function (Product $record) {
                    // Directly access the first element of the array
                    return is_array($record->pictures) ? $record->pictures[0] : null;
                })
                ->toggleable(true)
                ,


                TextColumn::make('name')
                    ->limit(80)
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()
                ,
                TextColumn::make('categories.name')
                    ->limit(80)
                    ->toggleable(true)
                    ->toggledHiddenByDefault()
                    ->searchable()
                    ->sortable()
                ,
                TextColumn::make('slug')
                    ->toggleable(true)
                    ->searchable()
                    ->sortable()
                ,
                BadgeColumn::make('active')
                    ->getStateUsing(function (Product $product) {
                        return $product->active == 1 ? "Active" : "Inactive";
                    })
                    ->sortable()
                    ->color(fn ($state) => match($state) {
                        'Active' => 'success',
                        'Inactive' => 'danger',
                    })
                    ->toggleable()
                    ->label('Status')
                    ->toggledHiddenByDefault()

                ,


            ])
            ->defaultSort('id', 'desc')

            ->filters([
                SelectFilter::make('active')
                ->label('Status')
                ->options([
                    '1' => 'Active',
                    '0' => 'Inactive',
                ]),
                
            ])
            ->actions([
                Tables\Actions\ViewAction::make(),
                Tables\Actions\EditAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getRelations(): array
    {
        return [
            //
        ];
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListProducts::route('/'),
            'create' => Pages\CreateProducts::route('/create'),
            'edit' => Pages\EditProducts::route('/{record}/edit'),
        ];
    }
}
